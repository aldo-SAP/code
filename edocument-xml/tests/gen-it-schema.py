#!/usr/bin/env python3
"""Generates ../rules/it-schema-data.js from the FatturaPA XML schema (Schema_VFPA12_V1.2.3.xsd): the content model of every element of an Italian electronic
invoice (the elements in their order, the alternatives, how often) and the simple types of the leaf elements (base type, patterns, list of values, lengths, ranges).
rules/it-schema.js walks a document with it.

usage: gen-it-schema.py XSD-FILE [OUT.js]    (OUT.js defaults to ../rules/it-schema-data.js)
"""
import sys, os, json, hashlib
from lxml import etree

X = "{http://www.w3.org/2001/XMLSchema}"
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rules", "it-schema-data.js")
root = etree.parse(src).getroot()
TNS = root.get("targetNamespace")
ctypes = {c.get("name"): c for c in root.findall(X + "complexType")}
stypes = {s.get("name"): s for s in root.findall(X + "simpleType")}
globals_ = {e.get("name"): e for e in root.findall(X + "element")}

def occ(n):
    mn = int(n.get("minOccurs", "1")); mx = n.get("maxOccurs", "1")
    return mn, (-1 if mx == "unbounded" else int(mx))

simple_cache = {}
type_labels = {}     # simple type -> {value: the schema's own description of it (Italian)}
labels = {}          # element name -> {value: description}
def simple(name):
    """the facets of a named simple type, merged down to its XML Schema base type"""
    if name in simple_cache:
        return simple_cache[name]
    r = stypes[name].find(X + "restriction")
    base = r.get("base")
    if base.startswith("xs:"):
        d = {"b": base[3:]}
    else:
        d = json.loads(json.dumps(simple(base)))
    pats, enums = [], []
    for f in r:
        if not isinstance(f.tag, str): continue
        ln = etree.QName(f).localname
        v = f.get("value")
        if ln == "pattern": pats.append(v)
        elif ln == "enumeration":
            enums.append(v)
            doc = f.find(".//" + X + "documentation")
            if doc is not None and doc.text and doc.text.strip():
                type_labels.setdefault(name, {})[v] = " ".join(doc.text.split())
        elif ln == "length": d["len"] = int(v)
        elif ln == "minLength": d["min"] = int(v)
        elif ln == "maxLength": d["max"] = int(v)
        elif ln == "minInclusive": d["lo"] = v
        elif ln == "maxInclusive": d["hi"] = v
        elif ln == "whiteSpace": d["ws"] = v
        elif ln == "annotation": pass
        else: raise ValueError("facet %s is not handled (%s)" % (ln, name))
    if pats: d.setdefault("p", []).append(pats)      # every level must match; the patterns of one level are alternatives
    if enums: d["e"] = enums
    simple_cache[name] = d
    return d

types, tid, eltypes = {}, {}, {}
def type_id(name):
    if name in tid:
        return tid[name]
    n = "t%d" % len(tid)
    tid[name] = n
    if name.startswith("xs:"):
        types[n] = {"v": {"b": name[3:]}}
    elif name in stypes:
        types[n] = {"v": simple(name)}
    else:
        c = ctypes[name]
        attrs = {}
        for a in c.findall(X + "attribute"):
            attrs[a.get("name")] = [type_id(a.get("type")), 1 if a.get("use") == "required" else 0]
        seq = c.find(X + "sequence")
        types[n] = {"m": model(seq)}
        if attrs: types[n]["a"] = attrs
    return n

def model(node):
    ln = etree.QName(node).localname
    mn, mx = occ(node)
    if ln == "element":
        if node.get("ref"):
            return ["x", node.get("ref"), mn, mx]       # ds:Signature: not looked into
        t = node.get("type")
        tid_ = type_id(t)
        if t in type_labels: labels[node.get("name")] = type_labels[t]
        return ["e", node.get("name"), tid_, mn, mx]
    if ln == "sequence":
        return ["s", [model(k) for k in node if isinstance(k.tag, str) and etree.QName(k).localname != "annotation"], mn, mx]
    if ln == "choice":
        return ["c", [model(k) for k in node if isinstance(k.tag, str) and etree.QName(k).localname != "annotation"], mn, mx]
    raise ValueError(ln)

roots = {}
for name, e in globals_.items():
    roots[TNS + "|" + name] = type_id(e.get("type"))

data = {
    "version": "FatturaPA XML schema v1.2.3 (Schema_VFPA12_V1.2.3.xsd), sha256 " + hashlib.sha256(open(src, "rb").read()).hexdigest()[:16],
    "ns": TNS,
    "roots": roots,
    "types": types,
    "labels": labels,
}
with open(out, "w") as f:
    f.write("/* The content model of an Italian electronic invoice (FatturaPA), from its XML schema; generated by tests/gen-it-schema.py - do not edit. */\n")
    f.write("window.IT_SCHEMA = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(len(types), "types ->", os.path.getsize(out), "bytes")
