#!/usr/bin/env node
/* Writes ../sw.js, the service worker that lets the page work offline: it keeps the page's own files (every script and style index.html names, the fonts, the icons) and
   serves them when there is no network. Never a document you open: those do not go through the network. The cache name carries a hash of the files, so a new
   version replaces the old one. usage: node gen-sw.js [OUT]   (check-offline.js runs it to a temp file and compares) */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const refs = Array.from(html.matchAll(/(?:src|href)="([^":]+\.(?:js|css))"/g)).map((m) => m[1]);
const extra = ["manifest.webmanifest", "notices.html", "fonts/instrument-sans.woff2", "fonts/jetbrains-mono.woff2", "icons/icon-192.png", "icons/icon-512.png", "icons/icon-180.png", "icons/icon-maskable-512.png"];
const files = ["./", "index.html"].concat(Array.from(new Set(refs.filter((f) => f !== "sw.js").concat(extra))).sort());
const hash = crypto.createHash("sha256");
files.forEach((f) => { const p = path.join(root, f === "./" ? "index.html" : f); if (fs.existsSync(p)) hash.update(f + "\0").update(fs.readFileSync(p)); });
const out = `/* Generated by tests/gen-sw.js - do not edit. Keeps the page's own files so that it works offline. */
const CACHE = "edoc-${hash.digest("hex").slice(0, 12)}";
const FILES = ${JSON.stringify(files, null, 2)};
self.addEventListener("install", (e) => {
  // a file that is not there (the page can be hosted without the shared folder) is skipped, it does not stop the install
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => c.add(f).catch(() => {})))));
  self.skipWaiting();
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE && k.startsWith("edoc-")).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// online: the network, and the answer is kept; offline: what was kept
self.addEventListener("fetch", (e) => {
  const r = e.request;
  if (r.method !== "GET") return;
  const u = new URL(r.url);
  if (u.protocol !== "http:" && u.protocol !== "https:") return;
  e.respondWith(fetch(r).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(r, copy)); }
    return res;
  }).catch(() => caches.match(r, { ignoreSearch: true }).then((m) => m || (r.mode === "navigate" ? caches.match("index.html") : Response.error()))));
});
`;
fs.writeFileSync(process.argv[2] || path.join(root, "sw.js"), out);
console.log((process.argv[2] ? "" : "sw.js: ") + files.length + " files, " + out.match(/edoc-[0-9a-f]+/)[0]);
