// Builds countries/ae/it-messages.js (the Italian text of the PINT AE messages) from tests/ae-it.tsv and the official rules.
// Every message of the rules must have a translation and every line of the file must belong to a rule: otherwise it stops.
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const w = {}; global.window = w; require(path.join(root, "countries", "ae", "pint-ae-rules.js"));
const norm = (s) => s.replace(/\s+/g, " ").trim();
const english = new Map();   // id → message
const add = (id, t) => { if (!english.has(id)) english.set(id, norm(t)); };
w.PINT_AE_RULES.patterns.forEach((p) => p.r.forEach((r) => r.a.forEach((a) => add(a[0], a[2]))));
const italian = new Map(fs.readFileSync(path.join(__dirname, "ae-it.tsv"), "utf8").split("\n").filter(Boolean).map((l) => { const i = l.indexOf("\t"); return [l.slice(0, i), l.slice(i + 1).trim()]; }));
const bad = [];
const out = {};
for (const [id, en] of english) {
  const it = italian.get(id);
  if (!it) { bad.push("no translation for " + id); continue; }
  if (out[en] && out[en] !== it) bad.push("two translations for the same message: " + id);
  out[en] = it;
}
// the self-billing variants of a rule have their own message
for (const [id, a] of Object.entries(w.PINT_AE_RULES.selfBilling)) if (!out[norm(a[2])]) bad.push("self-billing message of " + id + " has no translation");
for (const id of italian.keys()) if (!english.has(id)) bad.push("translation of an unknown rule " + id);
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
fs.writeFileSync(path.join(root, "countries", "ae", "it-messages.js"), "/* Italian text of the PINT AE messages (generated by tests/gen-ae-it.js from tests/ae-it.tsv; the English is the official text). */\nwindow.I18N && window.I18N.addItalian(" + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ");\n");
console.log(Object.keys(out).length + " messages translated");
