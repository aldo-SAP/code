#!/usr/bin/env node
/* Builds the "how to fix" lines (lib/help.js: EdocHelp.add) from tests/help-<set>.tsv (id<TAB>English<TAB>Italian) plus a template for the
   UBL-CR-nnn rules (an element EN 16931 has no field for). Usage: node gen-help.js */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const SETS = [
  ["en", "rules/help.js", "rules/en16931-rules.js", "EN16931_RULES", "EN 16931 and Peppol"],
  ["pp", "rules/help.js"], ["xsd", "rules/help.js"], ["fr", "countries/fr/help.js"], ["de", "countries/de/help.js"], ["ae", "countries/ae/help.js"]
];
function load(file, name) { global.window = {}; eval(fs.readFileSync(path.join(root, file), "utf8")); return window[name]; }
const tsv = (f) => (fs.existsSync(path.join(__dirname, f)) ? fs.readFileSync(path.join(__dirname, f), "utf8").split("\n").filter(Boolean).map((l) => l.split("\t")) : []);
// UBL-CR rules: "not(path)" says the document must not contain that element
function crHelp() {
  const out = {};
  const D = load("rules/en16931-rules.js", "EN16931_RULES");
  for (const p of D.patterns) for (const r of p.r) for (const a of r.a) {
    if (!/^UBL-CR-/.test(a[0]) || out[a[0]]) continue;
    const m = /^not\((.*)\)$/.exec(a[1].trim());
    const ctx = /^\/ubl:Invoice \| \/cn:CreditNote$/.test(r.c) ? "" : r.c + " → ";
    if (a[0] === "UBL-CR-002") out[a[0]] = ["Delete cbc:UBLVersionID from the root, or set it to 2.1.", "Elimina cbc:UBLVersionID dalla radice, oppure impostalo a 2.1."];
    else if (a[0] === "UBL-CR-412") out[a[0]] = ["Delete cac:PaymentMeans/cbc:PaymentDueDate: it is only allowed in a credit note. Put the due date in cbc:DueDate instead.", "Elimina cac:PaymentMeans/cbc:PaymentDueDate: è ammesso solo nella nota di credito. Indica la scadenza in cbc:DueDate."];
    else if (m) out[a[0]] = ["Delete " + ctx + m[1] + " from the XML: EN 16931 has no field for it, and some receivers reject the document.",
      "Elimina " + ctx + m[1] + " dall'XML: l'EN 16931 non prevede questo campo e alcuni destinatari rifiutano il documento."];
  }
  return out;
}
const files = {};
const add = (file, map) => { files[file] = Object.assign(files[file] || {}, map); };
add("rules/help.js", crHelp());
for (const [set, file] of SETS) {
  const map = {};
  tsv("help-" + set + ".tsv").forEach(([id, en, it]) => { if (id && en && it) map[id] = [en, it]; });
  add(file, map);
}
for (const [file, map] of Object.entries(files)) {
  const lines = Object.keys(map).sort().map((id) => "  " + JSON.stringify(id) + ": " + JSON.stringify(map[id]));
  fs.writeFileSync(path.join(root, file), "/* How to fix each rule, in plain words (generated by tests/gen-help.js from tests/help-*.tsv; do not edit). */\nEdocHelp.add({\n" + lines.join(",\n") + "\n});\n");
  console.log(file, Object.keys(map).length);
}
