// Builds countries/fr/messages.js (English and Italian text of the French messages) from tests/fr-en.tsv and tests/fr-it.tsv.
// The official messages are French (the BR-FR rules and part of BR-FREXT) or English (the rest of BR-FREXT); every message must have an Italian text and every
// French one an English text. A translation is written once for a message and applies to every id that has the same French text; {1}, {2} … stand for the
// <value-of/> values of the message in order. The messages with values become patterns.
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const w = {}; global.window = w;
["br-fr-rules.js", "frext-rules.js"].forEach((f) => require(path.join(root, "countries", "fr", f)));
const read = (f) => new Map(fs.readFileSync(path.join(__dirname, f), "utf8").split("\n").filter(Boolean).map((l) => { const i = l.indexOf("\t"); return [l.slice(0, i), l.slice(i + 1).trim()]; }));
const en = read("fr-en.tsv"), it = read("fr-it.tsv");
// the message of an assert with its values numbered: {1}, {2} …
const numbered = (m) => { let n = 0; return m.replace(/\u0002[^\u0003]*\u0003|\u0001/g, () => "{" + ++n + "}"); };
const looksFrench = (m) => /[éèêàçôûâîù’]|\b(Lorsque|Si le|Num Fact|doit|ne doit|Valeur actuelle)\b/.test(m);
const bad = [], byKey = new Map();   // numbered French text → first id
const E = { exact: {}, patterns: [] }, I = { exact: {}, patterns: [] };
const ids = new Set();
const entries = [];
[w.FR_RULES, w.FR_EXT_RULES].forEach((d) => d.patterns.forEach((p) => p.r.forEach((r) => r.a.forEach((a) => entries.push([a[0], a[2]])))));
entries.forEach(([id, msg]) => { ids.add(id); const k = numbered(msg); if (!byKey.has(k)) byKey.set(k, id); });
// the regular expression of a message: the text with each {n} a capture, the translation with {n} for the captured value
const put = (d, key, text) => {
  if (!/\{\d+\}/.test(key)) { d.exact[key] = text; return; }
  d.patterns.push([key.replace(/\{(\d+)\}/g, "{_v$1}"), text.replace(/\{(\d+)\}/g, "{_v$1}")]);
};
byKey.forEach((first, key) => {
  if (!it.has(first)) bad.push("no Italian text for " + first); else put(I, key, it.get(first));
  if (en.has(first)) put(E, key, en.get(first)); else if (looksFrench(key)) bad.push("no English text for the French message of " + first);
});
[...en.keys(), ...it.keys()].forEach((id) => { if (!ids.has(id)) bad.push("text of an unknown rule " + id); });
for (const [id, t] of [...en, ...it]) {   // the translation must use the same values as the message
  const k = entries.find(([i]) => i === id); if (!k) continue;
  const want = (numbered(k[1]).match(/\{\d+\}/g) || []).sort().join(), have = (t.match(/\{\d+\}/g) || []).sort().join();
  if (want !== have) bad.push(id + ": the translation has the values " + have + ", the message has " + want);
}
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
const dump = (d) => JSON.stringify(d.exact, null, 0).replace(/","/g, '",\n"') + ", " + JSON.stringify(d.patterns, null, 0).replace(/\],\[/g, "],\n[");
fs.writeFileSync(path.join(root, "countries", "fr", "messages.js"),
  "/* English and Italian text of the French messages (generated by tests/gen-fr-messages.js from tests/fr-en.tsv and tests/fr-it.tsv; the official text is French or English). */\n" +
  "window.I18N.addEnglish(" + dump(E) + ");\nwindow.I18N.addItalian(" + dump(I) + ");\n");
console.log(Object.keys(E.exact).length + E.patterns.length + " English, " + (Object.keys(I.exact).length + I.patterns.length) + " Italian (" + byKey.size + " different messages, " + entries.length + " asserts)");
