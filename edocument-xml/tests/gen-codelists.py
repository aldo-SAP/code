#!/usr/bin/env python3
"""Builds ../rules/codelists.js from the official EN 16931 UBL validation stylesheet
(ConnectingEurope/eInvoicing-EN16931, ubl/xslt/EN16931-UBL-validation.xslt).
Also reads the PEPPOL BIS lists from PEPPOL-EN16931-UBL.sch (OpenPEPPOL/peppol-bis-invoice-3, rules/sch) when given as a second argument.
Usage: gen-codelists.py path/to/EN16931-UBL-validation.xslt [path/to/PEPPOL-EN16931-UBL.sch]"""
import re, sys, json
X = open(sys.argv[1], encoding="utf-8").read()
RULES = {  # list name -> rule whose test carries the list
    "doc": "BR-CL-01", "docCreditNote": "BR-CL-01#2", "currency": "BR-CL-03", "vatPoint": "BR-CL-06", "objectScheme": "BR-CL-07", "noteSubject": "BR-CL-08",
    "icd": "BR-CL-10", "itemClass": "BR-CL-13", "country": "BR-CL-14", "payment": "BR-CL-16", "vatCategory": "BR-CL-17",
    "allowance": "BR-CL-19", "charge": "BR-CL-20", "unit": "BR-CL-23", "eas": "BR-CL-25",
}
out = {}
for name, rid in RULES.items():
    nth = 1
    if "#" in rid: rid, nth = rid.split("#"); nth = int(nth)
    i = X.find('name="id">' + rid + '<')
    seg = X[max(0, i - 60000):i]
    j = max(seg.rfind("<xsl:when test="), seg.rfind("<xsl:if test="))
    seg = seg[j:]
    m = re.findall(r"'((?: [A-Za-z0-9_.\-]+){2,} )'", seg)
    if not m:
        raise SystemExit("no list found for " + rid)
    out[name] = " ".join(sorted(set(m[nth - 1].split())))
if len(sys.argv) > 2:
    S = open(sys.argv[2], encoding="utf-8").read()
    for name, var in {"peppolMime": "MIMECODE", "peppolCharge": "UNCL7161", "peppolCurrency": "ISO4217", "peppolEas": "eaid", "peppolCountry": "ISO3166"}.items():
        m = re.search(r'name="%s"\s+value="tokenize\(\s*\'([^\']*)\'' % var, S)
        if not m: raise SystemExit("PEPPOL list not found: " + var)
        out[name] = " ".join(sorted(set(m.group(1).split())))
js = ("/* Code lists copied from the official EN 16931 UBL validation stylesheet (generated by tests/gen-codelists.py; do not edit). */\n"
      "window.EN16931_LISTS = {\n" + ",\n".join("  %s: %s" % (k, json.dumps(v)) for k, v in out.items()) + "\n};\n")
open(__import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)), "..", "rules", "codelists.js"), "w", encoding="utf-8").write(js)
print({k: len(v.split()) for k, v in out.items()})
