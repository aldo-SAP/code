#!/usr/bin/env python3
"""Generates ../lib/units-data.js from the UN/ECE Recommendation 20 (revision 11e, with the Recommendation 21 codes prefixed X) code list as published in the Peppol BIS
Billing 3.0 code lists (structure/codelist/UNECERec20-11e.xml): the unit code and its name, so the viewer can say what a unit code of an invoice line (BT-130, BT-150) is.
usage: gen-units.py UNECERec20-11e.xml [OUT.js]"""
import sys, os, json
from lxml import etree
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "units-data.js")
ns = {"c": "urn:fdc:difi.no:2017:vefa:structure:CodeList-1"}
root = etree.parse(src).getroot()
codes = {}
for c in root.findall("c:Code", ns):
    codes[c.find("c:Id", ns).text.strip()] = " ".join(c.find("c:Name", ns).text.split())
with open(out, "w", encoding="utf-8") as f:
    f.write("/* UN/ECE Recommendation 20 (revision 11e, with the Recommendation 21 codes) unit codes and names, from the Peppol BIS Billing 3.0 code list; generated by tests/gen-units.py - do not edit. */\n")
    f.write("window.UNIT_CODES = " + json.dumps(codes, separators=(",", ":"), ensure_ascii=False, sort_keys=True) + ";\n")
print(len(codes), "unit codes ->", os.path.getsize(out), "bytes")
