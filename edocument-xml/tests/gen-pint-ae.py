#!/usr/bin/env python3
"""Generates ../countries/ae/pint-ae-rules.js from the official PINT AE schematron (billing and self-billing).

usage: python3 gen-pint-ae.py .cache/pint-ae            (the folder fetch-artefacts.sh unpacks the official release into)

The official rules are plain ISO schematron: pattern → rule (context) → assert (XPath 2 test, message), all fatal. The page evaluates them
as they are, so no rule is re-written by hand; the output keeps the official ids, tests and messages untouched.
Invoice and credit note share the same rules; self-billing differs from billing in a single assert (ibr-cl-01, the document type codes).
"""
import sys, json, os
from lxml import etree

NS = {"s": "http://purl.oclc.org/dsdl/schematron"}
base = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), ".cache/pint-ae"))
here = os.path.dirname(os.path.abspath(__file__))


def load(variant, doctype, f):
    t = etree.parse(os.path.join(base, variant, doctype, "schematron", f + ".sch"))
    pats = []
    for pat in t.iterfind(".//s:pattern", NS):
        rules = []
        for rule in pat.iterfind("s:rule", NS):
            asserts = []
            for a in rule.iterfind("s:assert", NS):
                msg = " ".join("".join(a.itertext()).split())
                prefix = "[" + a.get("id") + "]-"
                if msg.startswith(prefix):
                    msg = msg[len(prefix):]
                asserts.append([a.get("id"), a.get("test"), msg, a.get("flag") or "fatal"])
            rules.append({"c": rule.get("context"), "a": asserts})
        pats.append({"id": pat.get("id"), "r": rules})
    return pats


FILES = ["PINT-UBL-validation-preprocessed", "PINT-jurisdiction-aligned-rules"]
billing = {f: load("billing", "trn-invoice", f) for f in FILES}
# invoice and credit note must be the same, else this generator has to be extended
for f in FILES:
    assert load("billing", "trn-creditnote", f) == billing[f], "invoice and credit note rules differ: " + f
    assert load("selfbilling", "trn-creditnote", f) == load("selfbilling", "trn-invoice", f), "self-billing invoice and credit note differ: " + f

sb_over = {}
for f in FILES:
    sb = load("selfbilling", "trn-invoice", f)
    b_flat = {a[0]: a for p in billing[f] for r in p["r"] for a in r["a"]}
    for p in sb:
        for r in p["r"]:
            for a in r["a"]:
                if b_flat.get(a[0]) != a:
                    sb_over[a[0]] = a
    assert {a[0] for p in sb for r in p["r"] for a in r["a"]} == set(b_flat), "self-billing has other rule ids than billing"

patterns = [p for f in FILES for p in billing[f]]
n = sum(len(r["a"]) for p in patterns for r in p["r"])
out = {"version": "1.0.4", "patterns": patterns, "selfBilling": sb_over}
js = ("/* PINT AE (UAE) validation rules, version 1.0.4: the official Peppol PINT AE schematron, all %d asserts, as published.\n"
      " * Generated by tests/gen-pint-ae.py from the official release package; edit the generator, not this file.\n"
      " * pattern → rules (XSLT match context) → asserts [id, XPath 2 test, message, flag]; selfBilling replaces the asserts that differ. */\n"
      "window.PINT_AE_RULES = %s;\n") % (n, json.dumps(out, ensure_ascii=False, separators=(",", ":")))
open(os.path.join(here, "..", "countries", "ae", "pint-ae-rules.js"), "w", encoding="utf-8").write(js)
print("%d asserts in %d patterns; self-billing replaces %s; %d bytes" % (n, len(patterns), sorted(sb_over), len(js)))
