// Builds countries/de/messages.js (English and Italian text of the XRechnung messages) from tests/de-en.tsv and tests/de-it.tsv.
// The official messages are German (BR-DE, BR-DEX, BR-TMP) or English (the Peppol rules); every message must have an Italian text and every German one
// an English text. Messages with <name/> or <value-of/> have {_n} / {_v} where the value goes and become patterns.
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const w = {}; global.window = w; require(path.join(root, "countries", "de", "xrechnung-rules.js"));
const read = (f) => new Map(fs.readFileSync(path.join(__dirname, f), "utf8").split("\n").filter(Boolean).map((l) => { const i = l.indexOf("\t"); return [l.slice(0, i), l.slice(i + 1).trim()]; }));
const en = read("de-en.tsv"), it = read("de-it.tsv");
const key = (m) => m.replace(/\u0001/g, "{_n}").replace(/\u0002[^\u0003]*\u0003/g, "{_v}");
// a message is translated into English when it is in de-en.tsv; the others must be English already
const looksGerman = (m) => /[äöüß]|\b(muss|müssen|wird|werden|und|oder|nicht|soll|sollen|dürfen|Wenn)\b/.test(m);
const bad = [], seen = new Set();
const E = { exact: {}, patterns: [] }, I = { exact: {}, patterns: [] };
const put = (d, k, v) => { if (/\{_[nv]\}/.test(k)) d.patterns.push([k, v]); else d.exact[k] = v; };
w.XRECHNUNG_RULES.patterns.forEach((p) => p.r.forEach((r) => r.a.forEach((a) => {
  const id = a[0], k = key(a[2]); seen.add(id);
  if (!it.has(id)) bad.push("no Italian text for " + id); else put(I, k, it.get(id));
  if (en.has(id)) put(E, k, en.get(id));
  else if (looksGerman(a[2])) bad.push("no English text for the German message of " + id);
})));
[...en.keys(), ...it.keys()].forEach((id) => { if (!seen.has(id)) bad.push("text of an unknown rule " + id); });
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
const dump = (d) => JSON.stringify(d.exact, null, 0).replace(/","/g, '",\n"') + ", " + JSON.stringify(d.patterns, null, 0).replace(/\],\[/g, "],\n[");
fs.writeFileSync(path.join(root, "countries", "de", "messages.js"),
  "/* English and Italian text of the XRechnung messages (generated by tests/gen-de-messages.js from tests/de-en.tsv and tests/de-it.tsv; the official text is German or English). */\n" +
  "window.I18N.addEnglish(" + dump(E) + ");\nwindow.I18N.addItalian(" + dump(I) + ");\n");
console.log(Object.keys(E.exact).length + E.patterns.length + " English, " + (Object.keys(I.exact).length + I.patterns.length) + " Italian");
