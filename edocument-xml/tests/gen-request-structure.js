#!/usr/bin/env node
// Writes ../lib/request-structure-fr.js from the structure file the platform provider gave for the French request (FR_STAGING_1.json): only the NAMES of the fields,
// at each level, never a value. lib/request-check.js compares a request with it.
// usage: gen-request-structure.js PROVIDER-FILE.json [OUT.js]
"use strict";
const fs = require("fs"), path = require("path");
const src = JSON.parse(fs.readFileSync(process.argv[2], "utf8")).req[0];
const out = process.argv[3] || path.join(__dirname, "..", "lib", "request-structure-fr.js");
// a level: its fields, and the lists it holds (a list: the union of the fields of its rows)
function level(obj) {
  const keys = [], lists = {};
  Object.keys(obj).forEach((k) => {
    if (Array.isArray(obj[k])) {
      const rows = obj[k].filter((r) => r && typeof r === "object");
      const merged = {};
      rows.forEach((r) => Object.keys(r).forEach((x) => { if (!(x in merged)) merged[x] = Array.isArray(r[x]) ? r[x] : ""; }));
      lists[k] = level(merged);
    } else keys.push(k);
  });
  return { keys, lists };
}
const data = level(src);
fs.writeFileSync(out, "/* The fields of the French request at each level (names only), from the structure file of the platform provider; generated by tests/gen-request-structure.js - do not edit. */\nwindow.REQUEST_STRUCTURE_FR = " + JSON.stringify(data) + ";\n");
const n = (l) => l.keys.length + Object.values(l.lists).reduce((t, x) => t + n(x), 0);
console.log(n(data) + " field names, lists: " + JSON.stringify(Object.keys(data.lists)) + " ->", fs.statSync(out).size, "bytes");
