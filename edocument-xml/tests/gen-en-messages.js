// Builds rules/messages.js (Italian text of the official EN 16931 and Peppol messages that the Italian dictionary of i18n.js does not have) from
// tests/en-it.tsv and tests/pp-it.tsv. The official messages are English; every message needs an Italian text (check-all-translations.js looks at all of them).
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const w = {}; global.window = w;
["en16931-rules.js", "peppol-rules.js"].forEach((f) => require(path.join(root, "rules", f)));
const read = (f) => new Map(fs.readFileSync(path.join(__dirname, f), "utf8").split("\n").filter(Boolean).map((l) => { const i = l.indexOf("\t"); return [l.slice(0, i), l.slice(i + 1).trim()]; }));
const key = (m) => m.replace(/\u0001/g, "{_n}").replace(/\u0002[^\u0003]*\u0003/g, "{_v}");
const messages = new Map();
[w.EN16931_RULES, w.PEPPOL_RULES].forEach((d) => d.patterns.forEach((p) => p.r.forEach((r) => r.a.forEach((a) => messages.set(a[0], key(a[2]))))));
const bad = [], exact = {}, patterns = [];
[["en-it.tsv", "EN 16931"], ["pp-it.tsv", "Peppol"]].forEach(([f, label]) => read(f).forEach((it, id) => {
  if (!messages.has(id)) { bad.push(label + ": text of an unknown rule " + id); return; }
  const k = messages.get(id);
  if (/\{_[nv]\}/.test(k)) patterns.push([k, it]); else exact[k] = it;
}));
if (bad.length) { console.error(bad.join("\n")); process.exit(1); }
const dump = (o, p) => JSON.stringify(o, null, 0).replace(/","/g, '",\n"') + ", " + JSON.stringify(p, null, 0).replace(/\],\[/g, "],\n[");
fs.writeFileSync(path.join(root, "rules", "messages.js"),
  "/* Italian text of official EN 16931 and Peppol messages (generated by tests/gen-en-messages.js from tests/en-it.tsv and tests/pp-it.tsv; the rest is in i18n.js). */\n" +
  "window.I18N.addItalian(" + dump(exact, patterns) + ");\n");
console.log(Object.keys(exact).length + patterns.length + " Italian texts");
