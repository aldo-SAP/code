#!/usr/bin/env python3
"""Generates ../lib/currency-data.js from the ISO 4217 currency code list as published in the Peppol BIS Billing 3.0 code lists (structure/codelist/ISO4217_2015.xml): the code and
its name, so the viewer can name every currency code of an invoice (BT-5, BT-6 and the currency of an amount), also the ones the browser has no name for.
usage: gen-currency.py ISO4217_2015.xml [OUT.js]"""
import sys, os, json
from lxml import etree
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "currency-data.js")
ns = {"c": "urn:fdc:difi.no:2017:vefa:structure:CodeList-1"}
codes = {}
for c in etree.parse(src).getroot().findall("c:Code", ns):
    codes[c.find("c:Id", ns).text.strip()] = " ".join(c.find("c:Name", ns).text.split())
with open(out, "w", encoding="utf-8") as f:
    f.write("/* ISO 4217 currency codes and names, from the Peppol BIS Billing 3.0 code list; generated by tests/gen-currency.py - do not edit. */\n")
    f.write("window.CURRENCY_CODES = " + json.dumps(codes, separators=(",", ":"), ensure_ascii=False, sort_keys=True) + ";\n")
print(len(codes), "currency codes ->", os.path.getsize(out), "bytes")
